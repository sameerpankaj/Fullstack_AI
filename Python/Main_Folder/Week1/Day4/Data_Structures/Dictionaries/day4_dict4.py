#Iteration

# Creating a dictionary with student information (key-value pairs)
student_dict = {'name': 'Alice', 'age': 25, 'grade': 'A'}

# Looping through the dictionary using items()
# items() returns both key and value at the same time
for key, value in student_dict.items():
    # Printing each key and its corresponding value
    print(key, value)
