# Creating a dictionary with student information (key-value pairs)
student_dict = {'name': 'Alice', 'age': 25, 'grade': 'A'}

# Printing the entire dictionary
print(student_dict)

# Accessing and printing value using key 'name'
print(student_dict['name'])

# Accessing and printing value using key 'age'
print(student_dict['age'])

# Accessing and printing value using key 'grade'
print(student_dict['grade'])