'Array Indexing'

# Import the NumPy library and assign it the alias 'np'
import numpy as np

# Create a NumPy array with five elements
arr = np.array([10, 20, 30, 40, 50])

# Access and print the element at index 2 (third element, because indexing starts at 0)
print(arr[2])

# Access and print the last element using negative indexing
print(arr[-1])